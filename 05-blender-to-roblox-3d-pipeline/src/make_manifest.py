# Writes game/src/shared/WeaponMeshes.luau from meshes/meta.json (Blender piece boxes) and
# meshes/ids.json (piece name -> "rbxassetid://N", filled after the Open Cloud upload).
# Run with D.A.V.E.'s bundled Python:  python make_manifest.py
import json, os

ROOT = os.path.dirname(os.path.abspath(__file__))
meta = json.load(open(os.path.join(ROOT, "meta.json"), encoding="utf-8"))
ids_path = os.path.join(ROOT, "ids.json")
ids = json.load(open(ids_path, encoding="utf-8")) if os.path.exists(ids_path) else {}
OUT = os.path.join(ROOT, "..", "game", "src", "shared", "WeaponMeshes.luau")
# smooth skin-kit shapes (meshes/build_kit_shapes.py, 22.11.2026); "" until uploaded -> kits use their old parts
KIT_SHAPES = ["KSpike", "KCrystal", "KBlade", "KLeaf", "KPetal", "KRod1", "KRod2", "KRod3", "KGem", "KRing1", "KRing2", "KRing3"]


def num(x):
    s = ("%.4f" % x).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def vec(v):
    return "{ " + ", ".join(num(x) for x in v) + " }"


lines = [
    "-- GENERATED by meshes/make_manifest.py - do not edit by hand.",
    "-- Smooth Blender meshes of the weapons (20.11.2026): one entry per colour piece, in Handle space",
    "-- (pos = bbox centre, size = bbox size, studs). mesh = \"\" until the asset is uploaded; WeaponModels",
    "-- uses a weapon's meshes only when every piece has an id.",
    "return {",
    "\tPrimitives = {",
    "\t\tRoundBlock = \"%s\"," % ids.get("SB_RoundBlock", ""),
    "\t\tRoundWedge = \"%s\"," % ids.get("SB_RoundWedge", ""),
] + [
    "\t\t%s = \"%s\"," % (k, ids.get("SB_" + k, "")) for k in KIT_SHAPES
] + [
    "\t},",
    "\tWeapons = {",
]
done = 0
# Import 3D turns a GLB 180 degrees about Y (glTF faces +Z, Roblox -Z). Exports from 20.11.2026 13:00
# are pre-turned in Blender; meshes uploaded before that carry yaw = 180 here (ids.json "_yaw").
yaws = ids.get("_yaw", {})
for wid in sorted(meta):
    w = meta[wid]
    yaw = yaws.get(wid, 0)
    lines.append("\t\t%s = { tris = %d, pieces = {" % (wid, w["tris"]))
    for p in w["pieces"]:
        mid = ids.get(p["name"], "")
        done += 1 if mid else 0
        tr = p.get("transparency") or 0
        lines.append("\t\t\t{ name = \"%s\", mesh = \"%s\", pos = %s, size = %s, color = %s, mat = \"%s\"%s%s }," % (
            p["name"], mid, vec(p["pos"]), vec(p["size"]), vec(p["color"]), p["mat"],
            (", transparency = %s" % num(tr)) if tr else "", (", yaw = %d" % yaw) if yaw else ""))
    lines.append("\t\t} },")
lines += ["\t},", "}", ""]
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("pieces with ids:", done, "of", sum(len(w["pieces"]) for w in meta.values()))
